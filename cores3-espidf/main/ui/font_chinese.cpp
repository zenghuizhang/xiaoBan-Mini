void label_set_auto_font(lv_obj_t *label, int size)
{
    const char* text = lv_label_get_text(label);

    // 检查是否包含中文字符（UTF-8）
    bool has_chinese = false;
    for (int i = 0; text[i] != '\0'; i++) {
        if ((uint8_t)text[i] >= 0xE0) {  // UTF-8中文字符起始字节
            has_chinese = true;
            break;
        }
    }

    const lv_font_t* font;
    if (has_chinese) {
        switch(size) {
            case 24: font = font_chinese_24(); break;
            case 20: font = font_chinese_20(); break;
            default: font = font_chinese_16(); break;
        }
    } else {
        switch(size) {
            case 24: font = &lv_font_montserrat_22; break;
            case 20: font = &lv_font_montserrat_18; break;
            case 18: font = &lv_font_montserrat_18; break;
            default: font = &lv_font_montserrat_14; break;
        }
    }

    lv_obj_set_style_text_font(label, font, 0);
}
