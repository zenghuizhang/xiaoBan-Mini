void font_chinese_init(void)
{
    ESP_LOGI(TAG, "========================================");
    ESP_LOGI(TAG, "  中文字体模块初始化");
    ESP_LOGI(TAG, "========================================");
    ESP_LOGI(TAG, "  内置字符数: %d", FONT_MAP_COUNT);
    ESP_LOGI(TAG, "  字体大小: 16px, 20px, 24px");
    ESP_LOGI(TAG, "  回退字体: montserrat");

    // 设置字体DPI
    lv_disp_t * disp = lv_disp_get_default();
    if (disp) {
        lv_disp_set_dpi(disp, 160);
    }

    ESP_LOGI(TAG, "========================================");
    ESP_LOGI(TAG, "✓ 中文字体已就绪");
    ESP_LOGI(TAG, "========================================");
}

