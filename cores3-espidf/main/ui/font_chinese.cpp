#define FONT_MAP_COUNT (sizeof(font_map) / sizeof(font_map[0]))

// ==============================================
// LVGL 字体回调函数
// ==============================================

static int font_16_height = 16;
static int font_16_baseline = 12;

static bool _font_get_glyph_dsc_cb(const lv_font_t * font, lv_font_glyph_dsc_t * dsc_out,
                                  uint32_t unicode_letter, uint32_t unicode_letter_next)
{
    // ASCII字符使用系统字体
    if (unicode_letter < 0x80) {
        dsc_out->adv_w = 8;
        dsc_out->box_h = font_16_height;
        dsc_out->box_w = 8;
        dsc_out->ofs_x = 0;
        dsc_out->ofs_y = 0;
        dsc_out->bpp = 1;
        return true;
    }

    // 中文字符 - 固定宽度
    dsc_out->adv_w = 16;
    dsc_out->box_h = font_16_height;
    dsc_out->box_w = 16;
    dsc_out->ofs_x = 0;
    dsc_out->ofs_y = font_16_baseline - font_16_height;
    dsc_out->bpp = 1;
    return true;
}

static const uint8_t* _get_chinese_bitmap(const char* utf8_str)
{
    // 简单的UTF-8匹配（假设是完整的中文字符UTF-8）
    for (size_t i = 0; i < FONT_MAP_COUNT; i++) {
        if (strcmp(utf8_str, font_map[i].name) == 0) {
            return font_map[i].data;
        }
    }
    return NULL;
}

static const uint8_t * _font_get_glyph_bitmap_cb(const lv_font_t * font, uint32_t unicode_letter)
{
    // ASCII字符返回空（使用系统字体渲染）
    if (unicode_letter < 0x80) {
        return NULL;
    }
    // 这里简化处理，实际项目使用完整字库
    return NULL;
}

